func TestParseFragmentData(t *testing.T) {
	tests := []struct {
		name    string
		src     string
		missing bool // parse a nonexistent path instead of src
		want    domain.Fragment
	}{
		{
			name: "v0.1 golden",
			src: `# Generated by unbound-tui - do not edit
# Last updated: 2026-01-01T00:00:00Z

server:
local-zone: "example.com" refuse
local-data: "example.com. 300 IN A 192.0.2.1"

# unbound-tui:disabled
# local-zone: "old.example" transparent
# local-data: "old.example. 300 IN A 192.0.2.2"
`,
			want: domain.Fragment{Sections: []domain.Section{{
				Kind: "server",
				Entries: []domain.Entry{
					{Key: "local-zone", Value: `"example.com" refuse`},
					{Key: "local-data", Value: `"example.com. 300 IN A 192.0.2.1"`},
					{Key: "local-zone", Value: `"old.example" transparent`, Disabled: true},
					{Key: "local-data", Value: `"old.example. 300 IN A 192.0.2.2"`, Disabled: true},
				},
			}}},
		},
		{
			name: "stray top-level directive",
			src: `include: "/x.conf"
server:
`,
			want: domain.Fragment{Sections: []domain.Section{
				{Kind: "", Entries: []domain.Entry{{Key: "include", Value: `"/x.conf"`}}},
				{Kind: "server"},
			}},
		},
		{
			name: "section-header rule",
			src: `stub-zone:
name: "."
stub-addr: "10.0.0.1"
`,
			want: domain.Fragment{Sections: []domain.Section{{
				Kind: "stub-zone",
				Entries: []domain.Entry{
					{Key: "name", Value: `"."`},
					{Key: "stub-addr", Value: `"10.0.0.1"`},
				},
			}}},
		},
		{
			name: "quoting and repeated keys",
			src: `server:
local-zone: "a.com" transparent
local-zone: "a.com" transparent
`,
			want: domain.Fragment{Sections: []domain.Section{{
				Kind: "server",
				Entries: []domain.Entry{
					{Key: "local-zone", Value: `"a.com" transparent`},
					{Key: "local-zone", Value: `"a.com" transparent`},
				},
			}}},
		},
		{
			name: "new-format disabled block",
			src: `server:
local-zone: "example.com" refuse

# unbound-tui:disabled
# server:
# local-data: "old.example. 300 IN A 192.0.2.2"
# forward-zone:
# name: "."
# forward-addr: 192.0.2.53

# local-data: "x.example. 300 IN A 192.0.2.99"
`,
			want: domain.Fragment{Sections: []domain.Section{
				{
					Kind: "server",
					Entries: []domain.Entry{
						{Key: "local-zone", Value: `"example.com" refuse`},
						{Key: "local-data", Value: `"old.example. 300 IN A 192.0.2.2"`, Disabled: true},
					},
				},
				{
					Kind: "forward-zone",
					Entries: []domain.Entry{
						{Key: "name", Value: `"."`, Disabled: true},
						{Key: "forward-addr", Value: "192.0.2.53", Disabled: true},
					},
				},
			}},
		},
		{
			name: "prose lines in disabled block are skipped",
			src: `server:
local-zone: "example.com" refuse

# unbound-tui:disabled
# disabled while on vacation
# disabled for: vacation
# local-data: "old.example. 300 IN A 192.0.2.2"
`,
			want: domain.Fragment{Sections: []domain.Section{{
				Kind: "server",
				Entries: []domain.Entry{
					{Key: "local-zone", Value: `"example.com" refuse`},
					{Key: "local-data", Value: `"old.example. 300 IN A 192.0.2.2"`, Disabled: true},
				},
			}}},
		},
		{
			name: "directive-looking line in disabled block still parses",
			src: `forward-zone:
name: "."

# unbound-tui:disabled
# name: "."
# forward-addr: 192.0.2.53
`,
			want: domain.Fragment{Sections: []domain.Section{{
				Kind: "forward-zone",
				Entries: []domain.Entry{
					{Key: "name", Value: `"."`},
					{Key: "name", Value: `"."`, Disabled: true},
					{Key: "forward-addr", Value: "192.0.2.53", Disabled: true},
				},
			}}},
		},
		{
			name: "CRLF",
			src:  "server:\r\nlocal-zone: \"a.com\" refuse\r\n",
			want: domain.Fragment{Sections: []domain.Section{{
				Kind:    "server",
				Entries: []domain.Entry{{Key: "local-zone", Value: `"a.com" refuse`}},
			}}},
		},
		{
			name:    "missing file",
			missing: true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if tt.missing {
				got, err := ParseFragment(filepath.Join(t.TempDir(), "absent.conf"))
				if err != nil {
					t.Fatalf("ParseFragment(absent) = %v, want nil", err)
				}
				if len(got.Sections) != 0 {
					t.Fatalf("ParseFragment(absent) = %+v, want empty", got)
				}
				return
			}

			got, err := parseFragment([]byte(tt.src))
			if err != nil {
				t.Fatalf("parseFragment() error: %v", err)
			}
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("parseFragment() =\n%+v\nwant\n%+v", got, tt.want)
			}
		})
	}
}

// TestScanConfig pins the raw item stream the refactored walker consumes: the
// two existing goldens plus an include line, exercising active entries,
// disabled-block context (including commented headers) and prose skipping.
func TestScanConfig(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want []scanItem
	}{
		{
			name: "v0.1 golden",
			src: `# Generated by unbound-tui - do not edit
# Last updated: 2026-01-01T00:00:00Z

server:
local-zone: "example.com" refuse
local-data: "example.com. 300 IN A 192.0.2.1"

# unbound-tui:disabled
# local-zone: "old.example" transparent
# local-data: "old.example. 300 IN A 192.0.2.2"
`,
			want: []scanItem{
				{header: true, kind: "server"},
				{entry: domain.Entry{Key: "local-zone", Value: `"example.com" refuse`}},
				{entry: domain.Entry{Key: "local-data", Value: `"example.com. 300 IN A 192.0.2.1"`}},
				{
					entry:      domain.Entry{Key: "local-zone", Value: `"old.example" transparent`, Disabled: true},
					disabled:   true,
					groupStart: true,
				},
				{
					entry:    domain.Entry{Key: "local-data", Value: `"old.example. 300 IN A 192.0.2.2"`, Disabled: true},
					disabled: true,
				},
			},
		},
		{
			name: "new-format disabled block",
			src: `server:
local-zone: "example.com" refuse

# unbound-tui:disabled
# server:
# local-data: "old.example. 300 IN A 192.0.2.2"
# forward-zone:
# name: "."
# forward-addr: 192.0.2.53

# local-data: "x.example. 300 IN A 192.0.2.99"
`,
			want: []scanItem{
				{header: true, kind: "server"},
				{entry: domain.Entry{Key: "local-zone", Value: `"example.com" refuse`}},
				{header: true, kind: "server", disabled: true, groupStart: true},
				{
					entry:    domain.Entry{Key: "local-data", Value: `"old.example. 300 IN A 192.0.2.2"`, Disabled: true},
					disabled: true,
				},
				{header: true, kind: "forward-zone", disabled: true},
				{entry: domain.Entry{Key: "name", Value: `"."`, Disabled: true}, disabled: true},
				{entry: domain.Entry{Key: "forward-addr", Value: "192.0.2.53", Disabled: true}, disabled: true},
			},
		},
		{
			name: "include line is an entry",
			src: `include: "/x.conf"
server:
`,
			want: []scanItem{
				{entry: domain.Entry{Key: "include", Value: `"/x.conf"`}},
				{header: true, kind: "server"},
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := scanConfig([]byte(tt.src))
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("scanConfig() =\n%+v\nwant\n%+v", got, tt.want)
			}
		})
	}
}
